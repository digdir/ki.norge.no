#!/usr/bin/env bash
#
# Start a local SQL Server container and wait until it accepts connections.
# All writes are local; nothing here touches a remote environment.
#
# Prints the sa password on the last line of stdout.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib.sh
. "$SCRIPT_DIR/lib.sh"

ENV_FILE="$KINORGE_DB_ENV_FILE"
RECREATE=1

usage() {
  cat >&2 <<EOF
usage: start-sqlserver.sh [--keep] [--port N]

  --keep     reuse a running container instead of recreating it
  --port N   host port to publish. Without it: MSSQL_PORT from .env, else 1433,
             moving to the next free port if that one is taken
EOF
  exit 1
}

PORT_OVERRIDE=""
while [ $# -gt 0 ]; do
  case "$1" in
    --keep) RECREATE=0; shift ;;
    --port) [ $# -ge 2 ] || usage; PORT_OVERRIDE="$2"; shift 2 ;;
    -h|--help) usage ;;
    *) log "unknown option: $1"; usage ;;
  esac
done

if [ -n "$PORT_OVERRIDE" ]; then
  case "$PORT_OVERRIDE" in
    *[!0-9]*) die "invalid --port value '$PORT_OVERRIDE': must be a number" ;;
  esac
fi

require_sqlcmd

# Sourced before the runtime is touched, so CONTAINER_CLI and MSSQL_IMAGE can
# be set here as well as in the environment.
if [ -f "$ENV_FILE" ]; then
  # shellcheck source=/dev/null
  . "$ENV_FILE"
fi

container_cli >/dev/null || die "no container runtime found. Install docker or podman."

# Real SQL Server is the default, because it is the engine Azure SQL is built on.
# It is native on x86_64. On Apple Silicon it runs under Rosetta (Colima with
# --vz-rosetta, or Docker Desktop with Rosetta), but segfaults under qemu.
# Azure SQL Edge is an arm64-native fallback; set MSSQL_IMAGE and
# MSSQL_PLATFORM in scripts/db/.env.
MSSQL_IMAGE="${MSSQL_IMAGE:-mcr.microsoft.com/mssql/server:2022-latest}"
MSSQL_PLATFORM="${MSSQL_PLATFORM:-linux/amd64}"

if [ -z "${MSSQL_SA_PASSWORD:-}" ]; then
  MSSQL_SA_PASSWORD="$(printf '%sAa1' "$(openssl rand -base64 24 | tr -dc 'A-Za-z0-9' | cut -c1-20)")"
fi
[ -n "$PORT_OVERRIDE" ] && MSSQL_PORT="$PORT_OVERRIDE"
MSSQL_PORT="${MSSQL_PORT:-1433}"

is_running() {
  cre ps --format '{{.Names}}' | grep -qx "$KINORGE_CONTAINER_NAME"
}

port_in_use() {
  tcp_check 127.0.0.1 "$1" 2
}

REUSE=0
if [ "$RECREATE" -eq 0 ] && is_running; then
  REUSE=1
else
  # Remove our own container first, so the port it held counts as free.
  cre rm -f "$KINORGE_CONTAINER_NAME" >/dev/null 2>&1 || true

  if port_in_use "$MSSQL_PORT"; then
    if [ -n "$PORT_OVERRIDE" ]; then
      die "port $MSSQL_PORT is already in use. Pick another with --port, or leave --port out to pick a free one."
    fi
    # Another SQL Server (e.g. info.altinn.no's container) often holds 1433.
    TAKEN="$MSSQL_PORT"
    LAST=$((MSSQL_PORT + 20))
    while port_in_use "$MSSQL_PORT"; do
      MSSQL_PORT=$((MSSQL_PORT + 1))
      [ "$MSSQL_PORT" -le "$LAST" ] || die "no free port between $TAKEN and $LAST. Pass one with --port."
    done
    log "port $TAKEN is in use, using $MSSQL_PORT"
  fi
fi

umask 077
mkdir -p "$(dirname "$ENV_FILE")"
cat >"$ENV_FILE" <<EOF
# Generated by start-sqlserver.sh. Local development only; git-ignored.
MSSQL_SA_PASSWORD='$MSSQL_SA_PASSWORD'
MSSQL_PORT=$MSSQL_PORT
MSSQL_IMAGE=$MSSQL_IMAGE
MSSQL_PLATFORM=$MSSQL_PLATFORM
${CONTAINER_CLI:+CONTAINER_CLI=$CONTAINER_CLI}
EOF
chmod 600 "$ENV_FILE"

log "image: $MSSQL_IMAGE ($MSSQL_PLATFORM), port $MSSQL_PORT"

start_container_fresh() {
  # Only this tool's own container and volume are removed.
  cre volume rm "$KINORGE_VOLUME_NAME" >/dev/null 2>&1 || true
  # Bound to 127.0.0.1 so the copy of prod data is not reachable from the network.
  # The password is passed by variable name, so it is not in the process list.
  MSSQL_SA_PASSWORD="$MSSQL_SA_PASSWORD" cre run -d \
    --name "$KINORGE_CONTAINER_NAME" \
    --platform "$MSSQL_PLATFORM" \
    -e ACCEPT_EULA=Y \
    -e MSSQL_SA_PASSWORD \
    -p "127.0.0.1:$MSSQL_PORT:1433" \
    -v "$KINORGE_VOLUME_NAME:/var/opt/mssql" \
    "$MSSQL_IMAGE" >/dev/null
}

if [ "$REUSE" -eq 1 ]; then
  log "reusing running container $KINORGE_CONTAINER_NAME"
else
  log "creating container $KINORGE_CONTAINER_NAME ..."
  start_container_fresh
fi

# Polled from the host: the Azure SQL Edge image ships no sqlcmd, so an
# in-container healthcheck cannot work for both images.
log "waiting for the database to accept connections ..."
# 127.0.0.1, not localhost: the port is published on IPv4 only, and the ODBC
# sqlcmd tries ::1 for localhost and waits out its login timeout there.
# The deadline is wall-clock, since a failed attempt itself takes up to -l seconds.
START_WAIT="$(date +%s)"
WAITED=0
until run_sqlcmd -S "127.0.0.1,$MSSQL_PORT" -U sa -P "$MSSQL_SA_PASSWORD" -C -l 5 -Q "SELECT 1" >/dev/null 2>&1; do
  RUNNING="$(cre inspect -f '{{.State.Running}}' "$KINORGE_CONTAINER_NAME" 2>/dev/null || echo unknown)"
  if [ "$RUNNING" = "false" ]; then
    EXIT_CODE="$(cre inspect -f '{{.State.ExitCode}}' "$KINORGE_CONTAINER_NAME" 2>/dev/null || echo '?')"
    log "container logs:"
    cre logs "$KINORGE_CONTAINER_NAME" 2>&1 | tail -15 >&2
    if [ "$EXIT_CODE" = "139" ]; then
      die "SQL Server segfaulted on startup (exit 139).

Your container runtime emulates x86 with qemu rather than Rosetta. Use Colima:
  colima start --vm-type=vz --vz-rosetta --cpu 4 --memory 8
or put this in scripts/db/.env to use the arm64-native engine:
  MSSQL_IMAGE=mcr.microsoft.com/azure-sql-edge
  MSSQL_PLATFORM=linux/arm64"
    fi
    die "the database container exited (code $EXIT_CODE) before becoming ready"
  fi

  if [ "$WAITED" -ge 180 ]; then
    log "container logs:"
    cre logs "$KINORGE_CONTAINER_NAME" 2>&1 | tail -20 >&2
    die "database did not become ready within 180s"
  fi
  sleep 5
  WAITED=$(( $(date +%s) - START_WAIT ))
done
WAITED=$(( $(date +%s) - START_WAIT ))

log "ready after ${WAITED}s"
printf '%s\n' "$MSSQL_SA_PASSWORD"
